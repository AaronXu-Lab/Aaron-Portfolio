import { build } from "esbuild";
import { readFile, writeFile, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
await rm("public/tools/wardrobe/chunks", { recursive: true, force: true });
const result = await build({
  metafile: true,
  entryPoints: ["src/lib/wardrobe/app.tsx"],
  outdir: "public/tools/wardrobe",
  entryNames: "app",
  chunkNames: "chunks/[name]-[hash]",
  splitting: true,
  bundle: true,
  format: "esm",
  minify: true,
  target: ["es2022"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "eof",
  banner: {
    js: "// Generated by npm run build:wardrobe. Edit src/lib/wardrobe/, not this bundle.",
  },
});
const staticFiles = new Set();
function visit(path) {
  if (staticFiles.has(path)) return;
  staticFiles.add(path);
  for (const entry of result.metafile.outputs[path]?.imports ?? [])
    if (entry.kind === "import-statement") visit(entry.path);
}
visit("public/tools/wardrobe/app.js");
const files = [
  "index.html",
  "app.js",
  "app.css",
  "icon-192.png",
  "icon-512.png",
  "icon-180.png",
  "manifest.webmanifest",
  ...[...staticFiles]
    .filter((f) => f.includes("/chunks/"))
    .map((f) => f.replace("public/tools/wardrobe/", "")),
];
const hash = createHash("sha256");
for (const f of files)
  hash.update(await readFile("public/tools/wardrobe/" + f));
hash.update(await readFile("scripts/build-wardrobe.mjs"));
const cache = "wardrobe-" + hash.digest("hex").slice(0, 12);
await writeFile(
  "public/tools/wardrobe/sw.js",
  `// Generated by build:wardrobe. Only the app shell is cached, never API requests or user photos.\nconst CACHE=${JSON.stringify(cache)};const SHELL=${JSON.stringify(["/tools/wardrobe/", ...files.map((f) => "/tools/wardrobe/" + f)])};\nself.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(SHELL)))});\nself.addEventListener('activate',e=>e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('wardrobe-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));\nself.addEventListener('fetch',e=>{const u=new URL(e.request.url);if(e.request.method!=='GET'||u.origin!==self.location.origin||!u.pathname.startsWith('/tools/wardrobe/'))return;if(e.request.mode==='navigate'){e.respondWith(fetch(e.request).catch(()=>caches.open(CACHE).then(c=>c.match('/tools/wardrobe/'))));return;}if(SHELL.includes(u.pathname))e.respondWith(caches.open(CACHE).then(c=>c.match(e.request,{ignoreSearch:true,ignoreVary:true})).then(r=>r||fetch(e.request)));});\n`,
);
